import { NextRequest, NextResponse } from "next/server";
import { createClient } from "@/lib/supabase/server";

function formatNaira(amount: number, currency: string) {
  const symbol = currency === "NGN" ? "₦" : currency === "GHS" ? "₵" : currency === "KES" ? "Ksh" : currency;
  return `${symbol}${Number(amount).toLocaleString("en-NG", { minimumFractionDigits: 2 })}`;
}

function toCSV(records: Record<string, unknown>[], currency: string): string {
  const header = ["Date", "Type", "Description", "Category", "Amount"].join(",");
  const rows = records.map((r) => [
    r.record_date,
    r.type === "sale" ? "Sale" : "Expense",
    `"${String(r.description ?? "").replace(/"/g, '""')}"`,
    `"${String(r.category ?? "").replace(/"/g, '""')}"`,
    formatNaira(Number(r.amount), currency),
  ].join(","));
  return [header, ...rows].join("\n");
}

