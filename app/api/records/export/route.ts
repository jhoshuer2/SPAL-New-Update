export async function GET(req: NextRequest) {
  try {
    const supabase = await createClient();
    const { data: { user } } = await supabase.auth.getUser();
    if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

    const { searchParams } = new URL(req.url);
    const startDate = searchParams.get("start_date");
    const endDate   = searchParams.get("end_date");
    const format    = searchParams.get("format") ?? "csv"; // csv | pdf

    if (!startDate || !endDate) {
      return NextResponse.json({ error: "start_date and end_date are required" }, { status: 400 });
    }

    // Fetch records in range
    const { data: records, error } = await supabase
      .from("records")
      .select("*")
      .eq("user_id", user.id)
      .gte("record_date", startDate)
      .lte("record_date", endDate)
      .order("record_date", { ascending: false })
      .order("created_at", { ascending: false });

    if (error) throw error;

    // Fetch user profile for currency + business name
    const { data: profile } = await supabase
      .from("users")
      .select("currency, business_name, full_name")
      .eq("id", user.id)
      .single();

    const currency     = profile?.currency ?? "NGN";
    const businessName = profile?.business_name ?? profile?.full_name ?? "My Business";

    if (format === "pdf") {
      const html = toPrintHTML(records ?? [], currency, startDate, endDate, businessName);
      return new NextResponse(html, {
        headers: {
          "Content-Type": "text/html; charset=utf-8",
        },
      });
    }

    // Default: CSV
    const csv      = toCSV(records ?? [], currency);
    const filename = `spal-records-${startDate}-to-${endDate}.csv`;
    return new NextResponse(csv, {
      headers: {
        "Content-Type":        "text/csv; charset=utf-8",
        "Content-Disposition": `attachment; filename="${filename}"`,
      },
    });
  } catch (err) {
    console.error("GET /api/records/export", err);
    return NextResponse.json({ error: "Export failed" }, { status: 500 });
  }
}
